"use client";

import { BASE } from "./base";

let voice: SpeechSynthesisVoice | null = null;

/** Higher is better: neural "Natural"/"Online" voices (Edge), Google's Mandarin voice (Chrome), then Apple's Premium/Enhanced. */
function score(v: SpeechSynthesisVoice): number {
  const n = v.name;
  let s = /^zh[-_]CN/i.test(v.lang) ? 10 : 0;
  if (/Natural|Neural/i.test(n)) s += 50;
  else if (/Online/i.test(n)) s += 40;
  else if (/Google/i.test(n)) s += 35;
  else if (/Premium/i.test(n)) s += 30;
  else if (/Enhanced/i.test(n)) s += 20;
  if (/Xiaoxiao|Yunxi|Xiaoyi|Lilian|Tingting|Yu-?shu/i.test(n)) s += 5;
  return s;
}

function pickVoice() {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return;
  const zh = window.speechSynthesis
    .getVoices()
    .filter((v) => /^zh/i.test(v.lang) && !/HK|TW|yue/i.test(v.lang));
  voice = zh.sort((a, b) => score(b) - score(a))[0] ?? null;
}

if (typeof window !== "undefined" && "speechSynthesis" in window) {
  pickVoice();
  window.speechSynthesis.addEventListener?.("voiceschanged", pickVoice);
}

/** True when recorded audio or a device Mandarin voice is available, so listening questions can be asked. */
export function hasChineseVoice(): boolean {
  if (manifest?.size) return true;
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return false;
  if (!voice) pickVoice();
  return !!voice;
}

export type SpeakResult = "ok" | "no-voice" | "unsupported";

/** Speaks Mandarin text with the device's own voice. Returns whether a Chinese voice was available. */
function deviceSpeak(text: string, rate: number, onEnd?: () => void): SpeakResult {
  if (typeof window === "undefined" || !("speechSynthesis" in window)) return "unsupported";
  if (!voice) pickVoice();
  const u = new SpeechSynthesisUtterance(text);
  u.lang = "zh-CN";
  u.rate = rate;
  if (voice) u.voice = voice;
  if (onEnd) u.onend = () => onEnd();
  window.speechSynthesis.cancel();
  window.speechSynthesis.speak(u);
  return voice ? "ok" : "no-voice";
}

/* Recorded neural-voice audio, generated by scripts/audio.py into /audio/<key>.mp3. The device voice is the fallback. */

let manifest: Set<string> | null = null;
let loading = false;
let current: HTMLAudioElement | null = null;

function loadManifest() {
  if (manifest || loading || typeof window === "undefined") return;
  loading = true;
  fetch(`${BASE}/audio/index.json`)
    .then((r) => (r.ok ? r.json() : []))
    .then((keys: string[]) => (manifest = new Set(keys)))
    .catch(() => (manifest = new Set()));
}
loadManifest();

/** cyrb53: a fast 53-bit string hash. scripts/audio.py computes the same keys. */
function cyrb53(str: string): string {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(16);
}

export interface SpeakOptions {
  /** Pinyin of a single character, so the recording uses that reading (行 xíng vs háng). */
  py?: string;
  /** "m" for the male voice, used for every other speaker in dialogues. */
  voice?: "m";
}

export function audioKey(text: string, opts: SpeakOptions = {}): string {
  let k = text.trim();
  if (opts.py && [...k].length === 1) k += "|" + opts.py.normalize("NFC").trim().toLowerCase();
  if (opts.voice) k = opts.voice + ":" + k;
  return cyrb53(k);
}

/** Stops whatever is playing, recorded or spoken. */
export function stopSpeech() {
  current?.pause();
  current = null;
  if (typeof window !== "undefined" && "speechSynthesis" in window) window.speechSynthesis.cancel();
}

/** Plays the recorded audio for the text when there is one, otherwise speaks it with the device's voice. */
export function speak(text: string, rate = 0.8, onEnd?: () => void, opts?: SpeakOptions): SpeakResult {
  if (typeof window === "undefined") return "unsupported";
  loadManifest();
  const key = audioKey(text, opts);
  if (!manifest?.has(key)) return deviceSpeak(text, rate, onEnd);
  stopSpeech();
  const a = new Audio(`${BASE}/audio/${key}.mp3`);
  a.playbackRate = rate;
  let done = false;
  const fallback = () => {
    if (done || current !== a) return;
    done = true;
    deviceSpeak(text, rate, onEnd);
  };
  a.onended = () => {
    if (!done && current === a) {
      done = true;
      onEnd?.();
    }
  };
  a.onerror = fallback;
  current = a;
  a.play().catch(fallback);
  return "ok";
}

/** Plays text `times` times with a pause between, the way exam recordings repeat. Returns a cancel function. */
export function speakTimes(text: string, times: number, rate = 0.8, onDone?: () => void): () => void {
  let cancelled = false;
  let timer: ReturnType<typeof setTimeout> | undefined;
  const play = (left: number) => {
    if (cancelled) return;
    const r = speak(text, rate, () => {
      if (left > 1) timer = setTimeout(() => play(left - 1), 1500);
      else onDone?.();
    });
    if (r === "unsupported") onDone?.();
  };
  play(times);
  return () => {
    cancelled = true;
    clearTimeout(timer);
    stopSpeech();
  };
}
