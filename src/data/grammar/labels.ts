export function grammarLabel(zh: string, locale: "en" | "ru"): string | null {
  const i = locale === "en" ? 0 : 1;
  if (GRAMMAR_LABELS[zh]) return GRAMMAR_LABELS[zh][i];
  const m = zh.match(/^(.*?)(\d+)$/);
  if (m && NUMBERED[m[1]]) return `${NUMBERED[m[1]][i]} ${m[2]}`;
  return null;
}
