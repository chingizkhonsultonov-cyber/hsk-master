"""Build per-level HSK 2.0 vocabulary files.

Inputs (downloaded into a raw folder, both MIT licensed):
  clem-N.json  official HSK 2.0 word list per level with the syllabus pinyin
               https://github.com/clem109/hsk-vocabulary
  old-N.json   the same words enriched with CC-CEDICT meanings, traditional forms,
               classifiers, part of speech and frequency
               https://github.com/drkameleon/complete-hsk-vocabulary
Usage: python3 scripts/build-vocab.py <raw dir>
"""
import json, pathlib, re, sys, unicodedata

raw = pathlib.Path(sys.argv[1])
out_dir = pathlib.Path(__file__).resolve().parent.parent / "src/data/hsk2"
out_dir.mkdir(parents=True, exist_ok=True)

def norm(p):
    p = unicodedata.normalize("NFC", p.lower()).replace("'", "").replace("’", "")
    return re.sub(r"[\s·-]", "", p)

def clean_meanings(ms):
    out = []
    for m in ms:
        for part in m.split(";"):
            part = part.strip()
            if not part or part.startswith("CL:") or re.match(r"^(variant|old variant|see|also written|used in|surname|abbr\.|\(bound form\)) ", part):
                continue
            if part not in out:
                out.append(part)
    return out[:5]

def load_glosses(lvl):
    """Curated learner glosses (English + Russian), one row per word number in the official list."""
    f = pathlib.Path(__file__).resolve().parent / "glosses" / f"hsk2-{lvl}.tsv"
    if not f.exists():
        return {}
    rows = [line.split("\t") for line in f.read_text(encoding="utf8").splitlines() if line.strip()]
    return {int(n): (en.split("; "), ru.split("; ")) for n, en, ru in rows}

lesson_size = {1: 10, 2: 10, 3: 15, 4: 20, 5: 25, 6: 25}
report = []
for lvl in range(1, 7):
    clem = json.loads((raw / f"clem-{lvl}.json").read_text(encoding="utf8"))
    rich = {w["simplified"]: w for w in json.loads((raw / f"old-{lvl}.json").read_text(encoding="utf8"))}
    glosses = load_glosses(lvl)
    words, unmatched = [], 0
    for i, c in enumerate(clem):
        h = c["hanzi"].strip()
        py = unicodedata.normalize("NFC", c["pinyin"].strip())
        r = rich.get(h)
        form = None
        if r:
            form = next((f for f in r["forms"] if norm(f["transcriptions"]["pinyin"]) == norm(py)), None)
        if form is None:
            unmatched += 1
        en = clean_meanings(form["meanings"]) if form else clean_meanings([t for t in c["translations"] if not t.startswith("CL:")])
        if not en:
            en = clean_meanings([t for t in c["translations"] if not t.startswith("CL:")])
        dict_en = en
        if (i + 1) in glosses:
            en, ru = glosses[i + 1]
        else:
            ru = []
        words.append({
            "id": f"2-{lvl}-{i + 1}",
            "h": h,
            "p": py,
            "t": form["traditional"] if form else h,
            "en": en,
            "ru": ru,
            "dict": [m for m in dict_en if m not in en][:4],
            "cl": form["classifiers"] if form else [],
            "pos": r["pos"] if r else [],
            "freq": r["frequency"] if r else 99999,
        })
    # Lessons: most frequent words first, so early lessons teach the words learners meet most.
    ordered = sorted(words, key=lambda w: w["freq"])
    size = lesson_size[lvl]
    for n, w in enumerate(ordered):
        w["lesson"] = n // size + 1
    (out_dir / f"level-{lvl}.json").write_text(json.dumps(ordered, ensure_ascii=False, separators=(",", ":")), encoding="utf8")
    report.append(f"HSK {lvl}: {len(words)} words, {ordered[-1]['lesson']} lessons, {unmatched} without exact CC-CEDICT form")
print("\n".join(report))

# Unique characters per level, in lesson order (used for writing progress).
chars_by_level = {}
for lvl in range(1, 7):
    seen = []
    for w in json.loads((out_dir / f"level-{lvl}.json").read_text(encoding="utf8")):
        for ch in w["h"]:
            if "一" <= ch <= "鿿" and ch not in seen:
                seen.append(ch)
    chars_by_level[lvl] = "".join(seen)
(out_dir.parent / "level-chars.ts").write_text(
    "/** Unique characters per level, in lesson order. Generated by scripts/build-vocab.py. */\n"
    "export const LEVEL_CHARS: Record<number, string> = " + json.dumps(chars_by_level, ensure_ascii=False) + ";\n",
    encoding="utf8",
)
